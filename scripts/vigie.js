#!/usr/bin/env node
'use strict';
// Vigie command line. Claude Code calls `vigie.js hook` for every event; people use the rest.

const fs = require('fs');
const path = require('path');
const http = require('http');
const { spawn } = require('child_process');

const ROOT = path.join(__dirname, '..');
const config = require('../lib/config');
const store = require('../lib/store');
const { buildRecord, guardOutput } = require('../lib/record');
const { summarise } = require('../lib/session');
const { rank } = require('../lib/risk');
const pkg = require('../package.json');

const argv = process.argv.slice(2);
const cmd = argv[0] || 'help';
const flag = (name) => argv.includes(`--${name}`);
const opt = (name, d) => {
  const i = argv.indexOf(`--${name}`);
  return i >= 0 && argv[i + 1] && !argv[i + 1].startsWith('--') ? argv[i + 1] : d;
};

function logError(cfg, err) {
  try {
    fs.mkdirSync(cfg.home, { recursive: true });
    fs.appendFileSync(path.join(cfg.home, 'errors.log'), `${new Date().toISOString()} ${err && err.stack ? err.stack : err}\n`);
  } catch {
    /* nothing else we can do */
  }
}

function readStdin(timeoutMs = 4000) {
  return new Promise((resolve) => {
    let buf = '';
    const done = () => resolve(buf);
    const timer = setTimeout(done, timeoutMs);
    process.stdin.setEncoding('utf8');
    process.stdin.on('data', (c) => (buf += c));
    process.stdin.on('end', () => {
      clearTimeout(timer);
      done();
    });
    process.stdin.on('error', () => {
      clearTimeout(timer);
      done();
    });
  });
}

// ---------- server management ----------

function serverInfoPath(cfg) {
  return path.join(cfg.home, 'server.json');
}

function readServerInfo(cfg) {
  try {
    return JSON.parse(fs.readFileSync(serverInfoPath(cfg), 'utf8'));
  } catch {
    return null;
  }
}

function health(port, timeout = 500) {
  return new Promise((resolve) => {
    const req = http.get({ host: '127.0.0.1', port, path: '/api/health', timeout, headers: { Host: `127.0.0.1:${port}` } }, (res) => {
      let b = '';
      res.on('data', (c) => (b += c));
      res.on('end', () => {
        try {
          const j = JSON.parse(b);
          resolve(j && j.app === 'vigie' ? j : null);
        } catch {
          resolve(null);
        }
      });
    });
    req.on('timeout', () => {
      req.destroy();
      resolve(null);
    });
    req.on('error', () => resolve(null));
  });
}

async function runningPort(cfg, timeout = 500) {
  const info = readServerInfo(cfg);
  if (info && info.port && (await health(info.port, timeout))) return info.port;
  if ((!info || info.port !== cfg.port) && (await health(cfg.port, timeout))) return cfg.port;
  return null;
}

function spawnServer() {
  const child = spawn(process.execPath, [path.join(__dirname, 'vigie.js'), 'serve', '--quiet'], {
    detached: true,
    stdio: 'ignore',
    windowsHide: true,
    env: process.env,
  });
  child.unref();
}

async function ensureServer(cfg, { wait = true } = {}) {
  const port = await runningPort(cfg, wait ? 500 : 200);
  if (port) return port;
  spawnServer();
  if (!wait) return null;
  for (let i = 0; i < 30; i++) {
    await new Promise((r) => setTimeout(r, 100));
    const p = await runningPort(cfg);
    if (p) return p;
  }
  return null;
}

function openBrowser(url) {
  const plat = process.platform;
  const [bin, args] = plat === 'darwin' ? ['open', [url]] : plat === 'win32' ? ['cmd', ['/c', 'start', '', url]] : ['xdg-open', [url]];
  try {
    const c = spawn(bin, args, { detached: true, stdio: 'ignore', windowsHide: true });
    c.on('error', () => {});
    c.unref();
    return true;
  } catch {
    return false;
  }
}

/** Small launcher in ~/.vigie so people can run the CLI outside Claude Code. */
function writeLauncher(cfg) {
  const target = path.join(__dirname, 'vigie.js');
  const body = `// Généré par Vigie : lance la version installée du plugin.\n// Generated by Vigie: runs the installed plugin version.\nrequire(${JSON.stringify(target)});\n`;
  const file = path.join(cfg.home, 'vigie.cjs');
  try {
    if (fs.existsSync(file) && fs.readFileSync(file, 'utf8') === body) return;
    fs.mkdirSync(cfg.home, { recursive: true });
    fs.writeFileSync(file, body);
  } catch {
    /* non-essential */
  }
}

// ---------- commands ----------

async function cmdHook() {
  const cfg = config.load();
  try {
    const raw = await readStdin();
    if (!raw.trim()) return;
    const payload = JSON.parse(raw);
    const rec = buildRecord(payload);
    const out = guardOutput(rec, cfg);
    store.append(cfg.home, rec);
    if (rec.event === 'SessionStart') {
      writeLauncher(cfg);
      if (cfg.autostart) await ensureServer(cfg, { wait: false });
    }
    if (out) process.stdout.write(JSON.stringify(out));
  } catch (err) {
    logError(cfg, err);
  }
}

async function cmdServe() {
  const cfg = config.load();
  const quiet = flag('quiet');
  const portArg = parseInt(opt('port', ''), 10);
  if (portArg) cfg.port = portArg;
  const existing = await runningPort(cfg);
  if (existing) {
    if (!quiet) console.log(`Vigie tourne déjà : http://localhost:${existing}`);
    return;
  }
  const { start } = require('../lib/server');
  const { server, port } = await start(cfg);
  fs.mkdirSync(cfg.home, { recursive: true });
  fs.writeFileSync(serverInfoPath(cfg), JSON.stringify({ pid: process.pid, port, version: pkg.version, startedAt: new Date().toISOString() }));
  store.prune(cfg.home, cfg.retentionDays);
  if (!quiet) console.log(`Vigie : http://localhost:${port}  (Ctrl+C pour arrêter)`);
  const stop = () => {
    try {
      const info = readServerInfo(cfg);
      if (info && info.pid === process.pid) fs.unlinkSync(serverInfoPath(cfg));
    } catch {
      /* ignore */
    }
    server.close();
    process.exit(0);
  };
  process.on('SIGINT', stop);
  process.on('SIGTERM', stop);
}

async function cmdOpen() {
  const cfg = config.load();
  const port = await ensureServer(cfg);
  if (!port) {
    console.log(cfg.lang === 'fr' ? 'Impossible de démarrer le tableau de bord. Lance `vigie doctor`.' : 'Could not start the dashboard. Run `vigie doctor`.');
    process.exitCode = 1;
    return;
  }
  const url = `http://localhost:${port}`;
  console.log(url);
  if (!flag('print')) openBrowser(url);
}

async function cmdTail() {
  const cfg = config.load();
  const port = await runningPort(cfg);
  const { run } = require('../lib/tui');
  run(cfg, {
    here: flag('here'),
    lang: opt('lang', cfg.lang),
    ascii: flag('ascii'),
    color: !flag('no-color'),
    history: parseInt(opt('history', '12'), 10),
    url: port ? `http://localhost:${port}` : null,
  });
  process.on('SIGINT', () => process.exit(0));
}

async function cmdStatusline() {
  const cfg = config.load();
  const lang = cfg.lang;
  let sid = null;
  try {
    sid = JSON.parse((await readStdin(1000)) || '{}').session_id;
  } catch {
    /* ignore */
  }
  let line = '👁 Vigie';
  if (sid) {
    const recs = store.readSession(cfg.home, sid);
    if (recs.length) {
      const s = summarise(sid, recs);
      const cur = s.current && s.current.title ? s.current.title[lang] : '';
      const short = cur.length > 48 ? cur.slice(0, 47) + '…' : cur;
      const risky = s.counts.risky ? ` · ⚠ ${s.counts.risky}` : '';
      line = `👁 ${short}${risky}`;
    }
  }
  const port = (readServerInfo(cfg) || {}).port;
  if (port) line += ` · localhost:${port}`;
  process.stdout.write(line);
}

function pickSession(cfg) {
  const id = opt('session');
  if (id) return id;
  const cwd = path.resolve(opt('cwd', process.cwd()));
  for (const f of store.listSessionFiles(cfg.home)) {
    const recs = store.readSession(cfg.home, f.id);
    const rcwd = recs.find((r) => r.cwd)?.cwd;
    if (rcwd && path.resolve(rcwd) === cwd) return f.id;
  }
  return store.listSessionFiles(cfg.home)[0]?.id || null;
}

function cmdRecap() {
  const cfg = config.load();
  const lang = opt('lang', cfg.lang);
  const id = pickSession(cfg);
  if (!id) {
    console.log(lang === 'fr' ? 'Aucune session enregistrée pour l’instant.' : 'No session recorded yet.');
    return;
  }
  const recs = store.readSession(cfg.home, id);
  const s = summarise(id, recs);
  const c = s.counts;
  const fr = lang === 'fr';
  const out = [];
  out.push(fr ? `Session « ${s.title || s.project} » (${s.project})` : `Session "${s.title || s.project}" (${s.project})`);
  out.push(fr
    ? `${c.prompts} demande(s), ${c.tools} action(s) : ${c.reads} lecture(s), ${c.edits} fichier(s) modifié(s), ${c.commands} commande(s), ${c.searches} recherche(s), ${c.web} accès web, ${c.agents} sous-agent(s), ${c.failures} échec(s).`
    : `${c.prompts} request(s), ${c.tools} action(s): ${c.reads} read(s), ${c.edits} file change(s), ${c.commands} command(s), ${c.searches} search(es), ${c.web} web call(s), ${c.agents} sub-agent(s), ${c.failures} failure(s).`);
  const changed = s.files.filter((f) => f.changed);
  if (changed.length) out.push((fr ? 'Fichiers modifiés : ' : 'Files changed: ') + changed.slice(0, 15).map((f) => f.display + (f.created ? (fr ? ' (créé)' : ' (new)') : '')).join(', '));
  const risky = recs.filter((r) => r.event === 'PreToolUse' && r.risk && rank(r.risk.level) >= rank('medium'));
  if (risky.length) {
    out.push(fr ? `Actions à surveiller (${risky.length}) :` : `Actions worth a look (${risky.length}):`);
    for (const r of risky.slice(0, 10)) out.push(`  - [${r.risk.level}] ${r.title[lang]} — ${r.risk.reasons[0][lang]}${r.guard ? (fr ? ' (Vigie a demandé confirmation)' : ' (Vigie asked for confirmation)') : ''}`);
  } else out.push(fr ? 'Aucune action risquée détectée.' : 'No risky action detected.');
  const info = readServerInfo(cfg);
  if (info && info.port) out.push((fr ? 'Tableau de bord : ' : 'Dashboard: ') + `http://localhost:${info.port}`);
  console.log(out.join('\n'));
}

async function cmdDemo() {
  const cfg = config.load();
  const file = path.join(ROOT, 'demo', 'demo-session.jsonl');
  const lines = fs.readFileSync(file, 'utf8').split('\n').filter(Boolean);
  const sid = `demo-${Date.now().toString(36)}`;
  const fast = flag('fast');
  if (!flag('no-open')) {
    const port = await ensureServer(cfg);
    if (port) {
      console.log(`http://localhost:${port}`);
      if (!flag('print')) openBrowser(`http://localhost:${port}`);
      if (!fast) await new Promise((r) => setTimeout(r, 1500));
    }
  }
  // In --fast mode, space the timestamps as if the session had happened over a few minutes.
  let clock = Date.now() - lines.length * 2500;
  for (const line of lines) {
    const p = JSON.parse(line);
    p.session_id = sid;
    const gap = p.hook_event_name === 'PreToolUse' ? 900 + Math.round(Math.random() * 2600) : p.hook_event_name === 'UserPromptSubmit' ? 8000 : 400;
    clock += gap;
    const rec = buildRecord(p, fast ? clock : Date.now());
    guardOutput(rec, cfg);
    store.append(cfg.home, rec);
    if (!fast) await new Promise((r) => setTimeout(r, p.hook_event_name === 'PreToolUse' ? 900 : p.hook_event_name === 'UserPromptSubmit' ? 1400 : 350));
  }
  console.log(cfg.lang === 'fr' ? `Démo rejouée (session ${sid}).` : `Demo replayed (session ${sid}).`);
}

async function cmdDoctor() {
  const cfg = config.load();
  const fr = cfg.lang === 'fr';
  const ok = (b) => (b ? '✓' : '✗');
  const major = parseInt(process.versions.node.split('.')[0], 10);
  let writable = false;
  try {
    fs.mkdirSync(cfg.home, { recursive: true });
    fs.accessSync(cfg.home, fs.constants.W_OK);
    writable = true;
  } catch {
    /* no */
  }
  const port = await runningPort(cfg);
  const sessions = store.listSessionFiles(cfg.home);
  const errors = fs.existsSync(path.join(cfg.home, 'errors.log')) ? fs.readFileSync(path.join(cfg.home, 'errors.log'), 'utf8').trim().split('\n').slice(-3) : [];
  console.log(`Vigie ${pkg.version}`);
  console.log(`${ok(major >= 18)} Node.js ${process.versions.node} ${major >= 18 ? '' : fr ? '(18 minimum requis)' : '(18 or newer required)'}`);
  console.log(`${ok(writable)} ${fr ? 'Dossier de données' : 'Data folder'} : ${cfg.home}`);
  console.log(`${ok(sessions.length > 0)} ${sessions.length} session(s) ${fr ? 'enregistrée(s)' : 'recorded'}${sessions.length ? '' : fr ? ' — lance Claude Code avec le plugin activé' : ' — start Claude Code with the plugin enabled'}`);
  console.log(`${ok(!!port)} ${fr ? 'Tableau de bord' : 'Dashboard'} : ${port ? `http://localhost:${port}` : fr ? 'arrêté (vigie open pour le lancer)' : 'stopped (run vigie open)'}`);
  console.log(`  ${fr ? 'Langue' : 'Language'}: ${cfg.lang} · ${fr ? 'garde-fou' : 'guard'}: ${cfg.guard} ${fr ? 'dès le niveau' : 'from level'} ${cfg.guardLevel} · port ${cfg.port}`);
  if (errors.length) console.log(`${fr ? 'Dernières erreurs' : 'Last errors'}:\n  ${errors.join('\n  ')}`);
}

function cmdConfig() {
  const sub = argv[1];
  if (sub === 'set' && argv[2]) {
    const val = argv[3];
    const next = config.save({ [argv[2]]: /^\d+$/.test(val) ? Number(val) : val === 'true' ? true : val === 'false' ? false : val });
    console.log(JSON.stringify(next, null, 2));
    return;
  }
  console.log(JSON.stringify(config.load(), null, 2));
}

function cmdHelp() {
  const fr = config.load().lang === 'fr';
  console.log(fr
    ? `Vigie ${pkg.version} — voir ce que fait Claude Code, en clair.

  vigie open           ouvre le tableau de bord dans le navigateur
  vigie tail           flux en direct dans le terminal (--here : projet courant, --ascii)
  vigie recap          résumé de la dernière session du dossier courant
  vigie demo           rejoue une session d'exemple (pour essayer sans Claude Code)
  vigie doctor         vérifie l'installation
  vigie config         affiche la configuration (config set guard off|ask|deny)
  vigie serve          lance le serveur du tableau de bord au premier plan`
    : `Vigie ${pkg.version} — see what Claude Code is doing, in plain words.

  vigie open           open the dashboard in your browser
  vigie tail           live feed in the terminal (--here: current project, --ascii)
  vigie recap          summary of the latest session for this folder
  vigie demo           replay a sample session (try it without Claude Code)
  vigie doctor         check the installation
  vigie config         show settings (config set guard off|ask|deny)
  vigie serve          run the dashboard server in the foreground`);
}

const COMMANDS = { hook: cmdHook, serve: cmdServe, open: cmdOpen, tail: cmdTail, statusline: cmdStatusline, recap: cmdRecap, demo: cmdDemo, doctor: cmdDoctor, config: cmdConfig, help: cmdHelp, '--help': cmdHelp, '-h': cmdHelp, version: () => console.log(pkg.version), '--version': () => console.log(pkg.version) };

Promise.resolve((COMMANDS[cmd] || cmdHelp)()).catch((err) => {
  if (cmd === 'hook') {
    logError(config.load(), err);
    process.exit(0); // a broken observer must never break Claude Code
  }
  console.error(err && err.message ? err.message : err);
  process.exit(1);
});
